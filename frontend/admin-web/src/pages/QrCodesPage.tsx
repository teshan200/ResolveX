import { useMemo, useState } from 'react'
import { Ban, CircleCheck, Eye, Info, QrCode as QrIcon } from 'lucide-react'
import { Avatar, Button, FilterChip, Modal, Pagination, SearchField, Select, StatusPill } from '../components/ui'
import { cn } from '../components/ui/cn'
import {
  qrBranchOptions,
  qrChipCounts,
  qrCodes,
  qrFormOptions,
  qrPageCount,
  totalQrCodes,
} from '../features/tenant-admin/mocks'
import type { QrCode } from '../features/tenant-admin/mocks'

type Chip = 'All' | 'Enabled' | 'Disabled'
const chips: Chip[] = ['All', 'Enabled', 'Disabled']

const head =
  'flex h-10 items-center gap-1 border-b border-line bg-canvas px-4 text-xs leading-4 font-semibold whitespace-nowrap text-content-secondary'
const cell = 'flex h-[60px] items-center gap-2 overflow-hidden px-4'

function QrStatus({ enabled }: { enabled: boolean }) {
  return enabled ? (
    <StatusPill tone="resolved" icon={CircleCheck}>
      Enabled
    </StatusPill>
  ) : (
    <StatusPill tone="neutral" icon={Ban}>
      Disabled
    </StatusPill>
  )
}

function Switch({ checked, label, onChange }: { checked: boolean; label: string; onChange: () => void }) {
  return (
    <button
      type="button"
      role="switch"
      aria-checked={checked}
      aria-label={label}
      onClick={onChange}
      className={cn(
        'relative h-5 w-9 shrink-0 cursor-pointer rounded-full transition-colors',
        'focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-line-focus',
        checked ? 'bg-brand' : 'bg-line-strong',
      )}
    >
      <span
        className={cn(
          'absolute top-0.5 left-0.5 size-4 rounded-full bg-surface transition-transform',
          checked && 'translate-x-4',
        )}
      />
    </button>
  )
}

function DetailRow({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="flex items-center gap-3 text-[13px] leading-4.5">
      <p className="min-w-0 flex-1 text-content-secondary">{label}</p>
      <div className="shrink-0 font-semibold whitespace-nowrap">{children}</div>
    </div>
  )
}

/** Tenant admin "QR codes" tab (Figma nodes 42:5477, 227:8177, 227:8510, 227:8803). Sample data. */
export function QrCodesPage() {
  const [enabled, setEnabled] = useState<Record<string, boolean>>(() =>
    Object.fromEntries(qrCodes.map((q) => [q.id, q.enabled])),
  )
  const [chip, setChip] = useState<Chip>('All')
  const [search, setSearch] = useState('')
  const [branch, setBranch] = useState(qrBranchOptions[0])
  const [form, setForm] = useState(qrFormOptions[0])
  const [page, setPage] = useState(1)
  const [preview, setPreview] = useState<QrCode | null>(null)
  const [disabling, setDisabling] = useState<QrCode | null>(null)

  const filtered = chip !== 'All' || search !== '' || branch !== qrBranchOptions[0] || form !== qrFormOptions[0]

  const rows = useMemo(() => {
    const q = search.trim().toLowerCase()
    return qrCodes.filter(
      (c) =>
        (chip === 'All' || (chip === 'Enabled') === enabled[c.id]) &&
        (!q || c.name.toLowerCase().includes(q) || c.id.toLowerCase().includes(q)) &&
        (branch === qrBranchOptions[0] || c.branch === branch) &&
        (form === qrFormOptions[0] || c.form === form),
    )
  }, [chip, search, branch, form, enabled])

  // The chips count every QR code in the company; the table holds the first page of them.
  const delta = qrCodes.filter((c) => enabled[c.id]).length - qrCodes.filter((c) => c.enabled).length
  const counts: Record<Chip, number> = {
    All: qrChipCounts.all,
    Enabled: qrChipCounts.enabled + delta,
    Disabled: qrChipCounts.disabled - delta,
  }

  const toggle = (c: QrCode) => (enabled[c.id] ? setDisabling(c) : setEnabled((s) => ({ ...s, [c.id]: true })))
  const confirmDisable = () => {
    if (disabling) setEnabled((s) => ({ ...s, [disabling.id]: false }))
    setDisabling(null)
    setPreview(null)
  }

  const summary = filtered
    ? `Showing ${rows.length ? `1–${rows.length}` : '0'} of ${rows.length} QR codes`
    : `Showing 1–${rows.length} of ${totalQrCodes} QR codes across 32 branches`

  return (
    <div className="flex flex-col gap-6">
      <header className="flex flex-col gap-1">
        <h1 className="text-2xl leading-8 font-semibold tracking-[-0.12px]">QR codes</h1>
        <p className="text-sm leading-5 text-content-secondary">
          QR codes generated by Branch Managers across all branches. Review, preview and enable or disable them —
          branches generate and name their own codes.
        </p>
      </header>

      <div className="flex h-[100px] items-center gap-3">
        <SearchField
          className="w-[260px]"
          placeholder="Search QR name or ID…"
          aria-label="Search QR codes"
          value={search}
          onChange={(e) => {
            setSearch(e.target.value)
            setPage(1)
          }}
        />
        <div className="w-[210px] shrink-0">
          <Select
            aria-label="Branch"
            options={qrBranchOptions}
            value={branch}
            onChange={(e) => {
              setBranch(e.target.value)
              setPage(1)
            }}
          />
        </div>
        <div className="w-[230px] shrink-0">
          <Select
            aria-label="Feedback form"
            options={qrFormOptions}
            value={form}
            onChange={(e) => {
              setForm(e.target.value)
              setPage(1)
            }}
          />
        </div>
        <div className="min-w-0 flex-1" />
        <div role="group" aria-label="QR status" className="flex gap-3">
          {chips.map((c) => (
            <FilterChip
              key={c}
              label={c}
              count={counts[c]}
              selected={chip === c}
              onClick={() => {
                setChip(c)
                setPage(1)
              }}
            />
          ))}
        </div>
      </div>

      <section className="flex flex-col overflow-hidden rounded-xl border border-line bg-surface">
        <div role="table" aria-label="QR codes">
          <div role="row" className="flex w-full">
            <div role="columnheader" className={cn(head, 'w-16 shrink-0')}>QR</div>
            <div role="columnheader" className={cn(head, 'min-w-0 flex-1')}>QR code</div>
            <div role="columnheader" className={cn(head, 'w-[110px] shrink-0')}>Branch</div>
            <div role="columnheader" className={cn(head, 'w-[180px] shrink-0')}>Feedback form</div>
            <div role="columnheader" className={cn(head, 'w-[150px] shrink-0')}>Created by</div>
            <div role="columnheader" className={cn(head, 'w-[110px] shrink-0')}>Created</div>
            <div role="columnheader" className={cn(head, 'w-[110px] shrink-0')}>Status</div>
            <div role="columnheader" className={cn(head, 'w-[90px] shrink-0')}>Enabled</div>
            <div role="columnheader" className={cn(head, 'w-[52px] shrink-0')} />
          </div>
          {rows.map((c) => {
            const on = enabled[c.id]
            return (
              <div
                key={c.id}
                role="row"
                className={cn('flex w-full border-b border-line-subtle', on ? 'bg-surface' : 'bg-canvas')}
              >
                <div className={cn(cell, 'w-16 shrink-0')}>
                  <span
                    className={cn(
                      'flex size-9 shrink-0 items-center justify-center overflow-hidden rounded-sm border border-line-subtle',
                      on ? 'bg-surface text-content' : 'bg-muted text-content-disabled',
                    )}
                  >
                    <QrIcon size={22} aria-hidden />
                  </span>
                </div>
                <div className={cn(cell, 'min-w-0 flex-1')}>
                  <div className={cn('min-w-0 flex-1 whitespace-nowrap', !on && 'text-content-tertiary')}>
                    <button
                      type="button"
                      onClick={() => setPreview(c)}
                      className="block w-full cursor-pointer truncate text-left text-sm leading-5 font-semibold"
                    >
                      {c.name}
                    </button>
                    <p className="truncate font-mono text-xs leading-4 font-medium text-content-tertiary">{c.id}</p>
                  </div>
                </div>
                <div className={cn(cell, 'w-[110px] shrink-0')}>
                  <p className="min-w-0 flex-1 truncate text-[13px] leading-4.5 text-content-secondary">{c.branch}</p>
                </div>
                <div className={cn(cell, 'w-[180px] shrink-0')}>
                  <p className="min-w-0 flex-1 truncate text-[13px] leading-4.5 text-content-secondary">{c.form}</p>
                </div>
                <div className={cn(cell, 'w-[150px] shrink-0')}>
                  <Avatar initials={c.createdBy.initials} size="sm" className="size-6!" />
                  <p className="min-w-0 flex-1 truncate text-[13px] leading-4.5 font-medium">{c.createdBy.name}</p>
                </div>
                <div className={cn(cell, 'w-[110px] shrink-0')}>
                  <p className="min-w-0 flex-1 truncate text-[13px] leading-4.5 text-content-secondary">{c.created}</p>
                </div>
                <div className={cn(cell, 'w-[110px] shrink-0')}>
                  <QrStatus enabled={on} />
                </div>
                <div className={cn(cell, 'w-[90px] shrink-0')}>
                  <Switch checked={on} label={`Enable ${c.name}`} onChange={() => toggle(c)} />
                </div>
                <div className={cn(cell, 'w-[52px] shrink-0')}>
                  <button
                    type="button"
                    aria-label={`Preview ${c.name}`}
                    onClick={() => setPreview(c)}
                    className="flex size-8 shrink-0 cursor-pointer items-center justify-center rounded-md text-content-tertiary hover:bg-muted"
                  >
                    <Eye size={16} aria-hidden />
                  </button>
                </div>
              </div>
            )
          })}
        </div>
        {rows.length === 0 && (
          <p className="px-5 py-10 text-center text-sm leading-5 text-content-secondary">No QR codes match these filters.</p>
        )}
        <div className="px-5 py-3">
          <Pagination summary={summary} page={page} pageCount={filtered ? 1 : qrPageCount} onPageChange={setPage} />
        </div>
      </section>

      <p className="flex items-start gap-2 text-xs leading-4 text-content-secondary">
        <Info size={14} className="mt-px shrink-0" aria-hidden />
        Disabling never deletes a QR code. Guests who scan a disabled code see an “inactive code” page, and its history
        and complaints stay intact.
      </p>

      <Modal
        open={preview !== null}
        title={preview?.name ?? ''}
        size="lg"
        topClass="pt-40"
        onClose={() => setPreview(null)}
        footer={
          <>
            <Button variant="outline" className="font-semibold!" onClick={() => setPreview(null)}>
              Close
            </Button>
            {preview && enabled[preview.id] && (
              <Button variant="destructive" className="font-semibold!" onClick={() => setDisabling(preview)}>
                Disable QR code
              </Button>
            )}
          </>
        }
      >
        {preview && (
          <>
            <p className="text-sm leading-5 text-content-secondary">
              {preview.id} · generated by {preview.createdBy.name} ({preview.createdByRole}, {preview.branchFull})
            </p>
            <div className="flex items-start gap-6">
              <div className="flex shrink-0 flex-col items-center gap-2 rounded-lg border border-line p-5">
                <div className="flex size-40 items-center justify-center">
                  <QrIcon size={140} strokeWidth={1.5} aria-hidden />
                </div>
                <p className="text-sm leading-5 font-semibold whitespace-nowrap">{preview.name}</p>
              </div>
              <div className="flex min-w-0 flex-1 flex-col gap-3">
                <DetailRow label="QR ID">
                  <span className="font-mono text-xs leading-4 font-medium">{preview.id}</span>
                </DetailRow>
                <DetailRow label="Branch">{preview.branchFull}</DetailRow>
                <DetailRow label="Feedback form">{preview.form}</DetailRow>
                <DetailRow label="Created by">
                  {preview.createdBy.name} · {preview.createdByRole}
                </DetailRow>
                <DetailRow label="Created">{preview.created}</DetailRow>
                <DetailRow label="Status">
                  <QrStatus enabled={enabled[preview.id]} />
                </DetailRow>
                <DetailRow label="Scans (30 days)">{preview.scans.toLocaleString('en-US')}</DetailRow>
              </div>
            </div>
          </>
        )}
      </Modal>

      <Modal
        open={disabling !== null}
        title={`Disable “${disabling?.name ?? ''}”?`}
        topClass="pt-40"
        onClose={() => setDisabling(null)}
        footer={
          <>
            <Button variant="outline" className="font-semibold!" onClick={() => setDisabling(null)}>
              Cancel
            </Button>
            <Button variant="destructive" className="font-semibold!" onClick={confirmDisable}>
              Disable QR code
            </Button>
          </>
        }
      >
        <p className="text-sm leading-5 text-content-secondary">
          Guests who scan it will see an inactive-code page. The QR record, its scans and complaints are kept — you can
          enable it again at any time.
        </p>
        {disabling && (
          <div className="flex items-center gap-3 rounded-lg border border-line p-3">
            <span className="flex size-10 shrink-0 items-center justify-center rounded-sm bg-canvas">
              <QrIcon size={24} aria-hidden />
            </span>
            <div className="min-w-0 flex-1 whitespace-nowrap">
              <p className="text-sm leading-5 font-semibold">{disabling.name}</p>
              <p className="text-xs leading-4 text-content-tertiary">
                {disabling.id} · {disabling.form}
              </p>
            </div>
          </div>
        )}
      </Modal>
    </div>
  )
}
